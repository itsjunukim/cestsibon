-- ============================================================================
-- 가평: 예약 환불금(refund) 컬럼 추가
-- ============================================================================
-- 예약금 과다 입금 후 일부 환불한 경우(예: 38만원 예약금 → 4만원 환불 → 실수령 34만원)
-- 그동안 표시할 방법이 없어 총 결제금액을 임의로 조정하던 문제를 해소한다.
--
-- 계산식
--   잔금(balance) = 총 결제금액(total_amount) - 예약금(deposit) + 환불금(refund)
--   실현 예약금  = 예약금(deposit) - 환불금(refund)
-- ============================================================================

ALTER TABLE public.reservations
  ADD COLUMN IF NOT EXISTS refund INTEGER NOT NULL DEFAULT 0;
